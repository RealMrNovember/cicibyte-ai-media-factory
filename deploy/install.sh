#!/usr/bin/env bash
# CiciByte AI Media Factory — one-command server install.
# Usage: bash deploy/install.sh
# Safe to re-run: an existing .env is never overwritten.
#
# There is no sign-in: protect the server at the network level. By default the panel is published on this
# machine's Tailscale address when Tailscale is running, otherwise on 127.0.0.1 only.
set -euo pipefail

cd "$(dirname "$0")/.."
COMPOSE=(docker compose -f deploy/docker-compose.yml --env-file .env)

command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required." >&2; exit 1; }

rand() { python3 -c "import secrets;print(secrets.token_urlsafe($1))" 2>/dev/null \
  || python -c "import secrets;print(secrets.token_urlsafe($1))" 2>/dev/null \
  || head -c "$1" /dev/urandom | base64 | tr -d '/+=\n'; }

if [ ! -f .env ]; then
  TS_IP="$(tailscale ip -4 2>/dev/null | head -n1 || true)"
  TS_FQDN="$(tailscale status --json 2>/dev/null | python3 -c 'import json,sys; print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))' 2>/dev/null || true)"
  HOSTS='"localhost","127.0.0.1"'
  if [ -n "$TS_IP" ]; then
    HOSTS="$HOSTS,\"$TS_IP\""
    [ -n "$TS_FQDN" ] && HOSTS="$HOSTS,\"$TS_FQDN\",\"${TS_FQDN%%.*}\""
  fi
  umask 077
  {
    echo "# Generated by deploy/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file secret."
    echo "MF_SECRET_KEY=$(rand 48)"
    echo "MF_DB_PASSWORD=$(rand 24)"
    echo "# Address the panel/API is published on. Never a public address: there is no sign-in."
    echo "MF_PUBLISH_ADDR=${TS_IP:-127.0.0.1}"
    echo "MF_BIND_PORT=${MF_BIND_PORT:-8080}"
    echo "# Host names the desktop app may use to reach this server (JSON list)."
    echo "MF_ALLOWED_HOSTS=[$HOSTS]"
  } > .env
  echo ".env created (secrets generated)."
else
  echo ".env exists; keeping it."
fi

"${COMPOSE[@]}" up -d --build

ADDR="$(grep -E '^MF_PUBLISH_ADDR=' .env | cut -d= -f2)"; ADDR="${ADDR:-127.0.0.1}"
PORT="$(grep -E '^MF_BIND_PORT=' .env | cut -d= -f2)"; PORT="${PORT:-8080}"
[ "$ADDR" = "0.0.0.0" ] && CHECK="127.0.0.1" || CHECK="$ADDR"
echo -n "Waiting for the server on ${CHECK}:${PORT} "
for _ in $(seq 1 90); do
  if curl -fsS "http://${CHECK}:${PORT}/api/health" >/dev/null 2>&1; then echo " ready."; break; fi
  echo -n "."; sleep 2
done
curl -fsS "http://${CHECK}:${PORT}/api/health" >/dev/null || { echo; echo "Server did not become healthy; see: ${COMPOSE[*]} logs api" >&2; exit 1; }

NAME="$(tailscale status --json 2>/dev/null | python3 -c 'import json,sys; print(json.load(sys.stdin)["Self"]["DNSName"].split(".")[0])' 2>/dev/null || true)"
echo
echo "Done. In the desktop app, open Settings → Server and enter:"
if [ -n "$NAME" ] && [ "$ADDR" != "127.0.0.1" ]; then
  echo "    http://${NAME}:${PORT}"
else
  echo "    http://${ADDR}:${PORT}   (bound to this machine only; see docs/DEPLOYMENT.md for remote access)"
fi
