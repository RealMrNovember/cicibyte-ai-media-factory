#!/usr/bin/env bash
# CiciByte AI Media Factory — one-command install.
# Usage: bash deploy/install.sh admin@example.com
# Safe to re-run: an existing .env is never overwritten, an existing admin is never reset.
set -euo pipefail

cd "$(dirname "$0")/.."
ADMIN_EMAIL="${1:-${ADMIN_EMAIL:-}}"
COMPOSE=(docker compose -f deploy/docker-compose.yml --env-file .env)

command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required." >&2; exit 1; }

rand() { python3 -c "import secrets;print(secrets.token_urlsafe($1))" 2>/dev/null \
  || python -c "import secrets;print(secrets.token_urlsafe($1))" 2>/dev/null \
  || head -c "$1" /dev/urandom | base64 | tr -d '/+=\n'; }

if [ ! -f .env ]; then
  umask 077
  {
    echo "# Generated by deploy/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file secret."
    echo "MF_SECRET_KEY=$(rand 48)"
    echo "MF_DB_PASSWORD=$(rand 24)"
    echo "MF_BIND_PORT=${MF_BIND_PORT:-8080}"
    echo 'MF_ALLOWED_HOSTS=["localhost","127.0.0.1"]'
  } > .env
  echo ".env created (secrets generated)."
else
  echo ".env exists; keeping it."
fi

"${COMPOSE[@]}" up -d --build

PORT="$(grep -E '^MF_BIND_PORT=' .env | cut -d= -f2)"
PORT="${PORT:-8080}"
echo -n "Waiting for the API on 127.0.0.1:${PORT} "
for _ in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:${PORT}/api/health" >/dev/null 2>&1; then echo " ready."; break; fi
  echo -n "."; sleep 2
done
curl -fsS "http://127.0.0.1:${PORT}/api/health" >/dev/null || { echo; echo "API did not become healthy; see: ${COMPOSE[*]} logs api" >&2; exit 1; }

if [ -n "$ADMIN_EMAIL" ]; then
  if "${COMPOSE[@]}" exec -T api mf create-admin --email "$ADMIN_EMAIL"; then
    echo "Log in at http://127.0.0.1:${PORT} with the password above."
  else
    echo "Admin already exists; keeping its password. To reset: ${COMPOSE[*]} exec api mf create-admin --email $ADMIN_EMAIL --reset"
  fi
else
  echo "No admin e-mail given. Create one with: ${COMPOSE[*]} exec api mf create-admin --email you@example.com"
fi
echo "Done. The panel is bound to 127.0.0.1 only; use Tailscale or a reverse proxy for remote access (docs/DEPLOYMENT.md)."
